const catalogs = Object.freeze({ 'pt-BR': catalog, 'en-US': enUS, 'es-ES': esES });
export const supportedLocales = Object.freeze(Object.keys(catalogs));
const localeStorageKey = 'creatordesk.locale';

export function setUiLocale(locale) {
  if (!Object.hasOwn(catalogs, locale)) return false;
  uiLocale = locale;
  return true;
}

export function readUiLocale(storage) {
  try {
    const stored = (storage ?? globalThis.localStorage)?.getItem(localeStorageKey);
    return Object.hasOwn(catalogs, stored) ? stored : 'pt-BR';
  } catch {
    return 'pt-BR';
  }
}

export function writeUiLocale(locale, storage) {
  if (!Object.hasOwn(catalogs, locale)) return false;
  try {
    const target = storage ?? globalThis.localStorage;
    if (!target) return false;
    target.setItem(localeStorageKey, locale);
    return true;
  } catch {
    return false;
  }
}

export function catalogKeys() {
  return Object.keys(catalog);
}

