export function t(key, parameters = {}) {
  const message = catalog[key] ?? key;
  return message.replace(/\{([\w.-]+)\}/g, (placeholder, name) => (
    Object.hasOwn(parameters, name) ? String(parameters[name]) : placeholder
  ));
}

export function apiErrorMessage(code) {
  return t(apiErrorKeys[code] ?? 'error.genericCode', { code });
}

export function formatNumber(value) {
  return new Intl.NumberFormat(uiLocale).format(value);
}

export function formatDateTime(value, options = { dateStyle: 'medium', timeStyle: 'short' }, timezone = 'UTC') {
  return new Intl.DateTimeFormat(uiLocale, { ...options, timeZone: timezone }).format(value);
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  });
}
