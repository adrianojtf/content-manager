export type FacebookOAuthErrorCode =
  | 'FACEBOOK_OAUTH_STATE_INVALID'
  | 'FACEBOOK_OAUTH_DENIED'
  | 'FACEBOOK_OAUTH_CODE_REQUIRED'
  | 'FACEBOOK_OAUTH_CONFIGURATION_REQUIRED'
  | 'FACEBOOK_OAUTH_CONFIGURATION_INVALID'
  | 'FACEBOOK_OAUTH_TOKEN_EXCHANGE_FAILED'
  | 'FACEBOOK_OAUTH_SCOPE_MISSING'
  | 'FACEBOOK_OAUTH_NO_MANAGED_PAGES'
  | 'FACEBOOK_OAUTH_PAGE_ACCESS_UNAVAILABLE'
  | 'FACEBOOK_OAUTH_PAGE_SELECTION_INVALID'
  | 'FACEBOOK_OAUTH_PROVIDER_UNAVAILABLE'
  | 'FACEBOOK_OAUTH_RESPONSE_INVALID'
  | 'FACEBOOK_OAUTH_CREDENTIAL_CLEANUP_FAILED';

export class FacebookOAuthError extends Error {
  constructor(readonly code: FacebookOAuthErrorCode) {
    super(code);
    this.name = 'FacebookOAuthError';
  }
}
