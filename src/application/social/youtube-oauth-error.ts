export type YouTubeOAuthErrorCode =
  | 'YOUTUBE_OAUTH_STATE_INVALID'
  | 'YOUTUBE_OAUTH_DENIED'
  | 'YOUTUBE_OAUTH_CODE_REQUIRED'
  | 'YOUTUBE_OAUTH_CONFIGURATION_REQUIRED'
  | 'YOUTUBE_OAUTH_CONFIGURATION_INVALID'
  | 'YOUTUBE_OAUTH_TOKEN_EXCHANGE_FAILED'
  | 'YOUTUBE_OAUTH_SCOPE_MISSING'
  | 'YOUTUBE_OAUTH_CHANNEL_NOT_FOUND'
  | 'YOUTUBE_OAUTH_PROVIDER_UNAVAILABLE'
  | 'YOUTUBE_OAUTH_RESPONSE_INVALID'
  | 'YOUTUBE_OAUTH_CREDENTIAL_CLEANUP_FAILED';

export class YouTubeOAuthError extends Error {
  constructor(readonly code: YouTubeOAuthErrorCode) {
    super(code);
    this.name = 'YouTubeOAuthError';
  }
}
