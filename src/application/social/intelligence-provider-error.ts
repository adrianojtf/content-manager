export type IntelligenceProviderErrorCode =
  | 'INTELLIGENCE_PROVIDER_CONFIGURATION_REQUIRED'
  | 'INTELLIGENCE_PROVIDER_CONFIGURATION_INVALID'
  | 'INTELLIGENCE_PROVIDER_DATA_POLICY_REQUIRED'
  | 'INTELLIGENCE_INPUT_INVALID'
  | 'INTELLIGENCE_PROVIDER_AUTHORIZATION_FAILED'
  | 'INTELLIGENCE_PROVIDER_RATE_LIMITED'
  | 'INTELLIGENCE_PROVIDER_UNAVAILABLE'
