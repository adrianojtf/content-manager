export type InstagramOAuthErrorCode =
  | 'INSTAGRAM_OAUTH_STATE_INVALID'
  | 'INSTAGRAM_OAUTH_DENIED'
  | 'INSTAGRAM_OAUTH_CODE_REQUIRED'
  | 'INSTAGRAM_OAUTH_CONFIGURATION_REQUIRED'
  | 'INSTAGRAM_OAUTH_CONFIGURATION_INVALID'
  | 'INSTAGRAM_OAUTH_TOKEN_EXCHANGE_FAILED'
  | 'INSTAGRAM_OAUTH_TOKEN_REFRESH_FAILED'
  | 'INSTAGRAM_OAUTH_SCOPE_MISSING'
  | 'INSTAGRAM_OAUTH_ACCOUNT_INVALID'
  | 'INSTAGRAM_OAUTH_ACCOUNT_ID_MISMATCH'
  | 'INSTAGRAM_OAUTH_PROVIDER_UNAVAILABLE'
  | 'INSTAGRAM_OAUTH_RESPONSE_INVALID'
  | 'INSTAGRAM_OAUTH_CREDENTIAL_CLEANUP_FAILED';

export class InstagramOAuthError extends Error {
  constructor(readonly code: InstagramOAuthErrorCode) {
    super(code);
    this.name = 'InstagramOAuthError';
  }
}
