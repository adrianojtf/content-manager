export type AnalyticsEntryErrorCode =
  | 'ANALYTICS_ENTRY_INPUT_INVALID'
  | 'ANALYTICS_ENTRY_SERIES_NOT_FOUND'
  | 'ANALYTICS_ENTRY_EPISODE_NOT_FOUND'
  | 'ANALYTICS_ENTRY_ACCOUNT_NOT_FOUND'
  | 'ANALYTICS_ENTRY_PUBLICATION_NOT_LINKED'
  | 'ANALYTICS_ENTRY_PUBLICATION_ALREADY_LINKED'
  | 'ANALYTICS_ENTRY_PLATFORM_UNSUPPORTED'
  | 'ANALYTICS_ENTRY_SERIES_CONFLICT'
  | 'ANALYTICS_ENTRY_EPISODE_CONFLICT'
  | 'ANALYTICS_ENTRY_CODE_CONFLICT'
  | 'ANALYTICS_ENTRY_SAVE_FAILED';

export class AnalyticsEntryError extends Error {
  constructor(readonly code: AnalyticsEntryErrorCode) {
    super(code);
    this.name = 'AnalyticsEntryError';
  }
}
